def initial(ch: str) -> str:
    """一个汉字的拼音首字母；不是基本区汉字 / 没有读音返回空串。"""
    code = ord(ch) if ch else 0
    if BASE <= code <= END:
        letter = TABLE[code - BASE]
        if letter != "?":
            return letter
    return ""


def known(text: str) -> bool:
    """这段字是不是都能查到首字母（调试/自检用）。"""
    return bool(text) and all(initial(ch) for ch in text)
