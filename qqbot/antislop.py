"""把"鱼八股"套话从回复里拿掉。

社区把 DeepSeek 的固定确认腔叫「鱼八股」，被点名最多的三句是：
「这条我记下了」「这条我认」「本鱼最喜欢的一句话」。

这些不是人设，是模型在"表示收到/承认/引用"时偷懒用的模板。

2026-10-26 又长出一批：模型学会了绕开「记下了」的检测，改用
「认了认了」「本鱼不认哦」「本鱼就不接这句了」这种**二选一表态**
（要不要认、要不要接），意思一样空。这类也只拦"表态"，不拦有具体对象的
拒绝（「本鱼不接广告」）和正常的认怂（「本鱼认错啦」「本鱼认输啦」）。

2026-10-30 的漏网：模型把后缀省掉了，回一句「精华液又是什么啦，这词本鱼不接」
就收尾——原来的句式要求「不接」后面跟 哦/了/啦 或 这句/这话，
光秃秃一个「本鱼不接」在句末反而漏了。现在多一条「句末裸表态」：
「不接/不认」顶在句末、后面只剩标点才算，带下文的拒绝
（「这张图本鱼不接。这是第 1/3 次提醒」）不动。

这里只做两件事：

1. `find()`：检测。命中就带着提示让模型重说一次（在 LLM 层做）
2. `strip()`：兜底。重说还带，就把那一小句删掉

不改写、不扩写，也不碰「本鱼认错啦」「本鱼认输啦」这类正常的认怂。
"""

from __future__ import annotations

import re

# 「认」只有在"认账"的意思下才是套话；认错/认输/认识/认出来都要留着
_NOT_ADMIT = r"(?![识错输真为得同可定购罪领出不账])"
_VERB = rf"(?:记(?:下|住|着)|收下|认{_NOT_ADMIT})"
_SUFFIX = r"(?:了|啦|哦|噢|喽|啰|吧|嘛|呀)"
_PUNCT = r"[，,。！？!?~～…\s]"
# 句末尾巴：标点、空白、引号/括号都算，别再往后有字
_TAIL = r"[，,。！？!?~～…\s”’'\"」』）)]"

# 顺序有讲究：带"这条/这个"的长模式要先跑，
# 否则先删掉"我记下了"会剩一个孤零零的"这条"。
_PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    # 本鱼最喜欢的一句话（拿来起头引用）
    ("最喜欢的一句话", re.compile(
        r"(?:^|[，,。！？!?\s])(?:我|本鱼)?最(?:喜欢|爱|认同)的一?句(?:话)?(?:是|：|:)?"
    )),
    # 这条我记下了 / 这个我认 / 这句话我收下了
    ("这条我认", re.compile(
        rf"(?:这|那)(?:条|个|句)(?:话)?(?:我|本鱼)?(?:都|也|先|就)?{_VERB}{_SUFFIX}?"
    )),
    # 我记下了 / 本鱼记住了 / 我收下了 / 本鱼认了
    ("记下认账", re.compile(rf"(?:我|本鱼)(?:都|也|先|就)?{_VERB}{_SUFFIX}")),
    # 记下了～ / 记住啦（没有主语的确认）
    ("记下了", re.compile(
        rf"(?:^|[，,。！？!?\s]){_VERB}{_SUFFIX}(?=[，,。！？!?~～…\s]|$)"
    )),
    # 本鱼不认哦 / 本鱼就不接这句了 / 蠢这个本鱼不认哦（二选一表态）
    ("不认不接", re.compile(
        rf"(?:本鱼|我)(?:也|就|都|可|还)?不(?:认{_NOT_ADMIT}|接)"
        rf"(?:(?:这句|这话|这个|这茬){_SUFFIX}?|{_SUFFIX})(?={_PUNCT}|$)"
    )),
    # 也不接哦 / 这话题就不接了（没有主语，但带"也/就/都"的表态）
    ("就不接了", re.compile(
        rf"(?:也|就|都)不接(?:这句|这话|这个|这茬)?{_SUFFIX}?(?={_PUNCT}|$)"
    )),
    # 这词本鱼不接 / 这个我不认（句末裸表态：不给理由、后面也没下文了）
    ("句末裸表态", re.compile(
        rf"(?:[，,]\s*)?(?:(?:这|那)(?:个|条|句|词|话|茬|种|事|事儿|话题|图))?"
        rf"(?:本鱼|我)(?:也|就|都|可|还)?(?:不接|不认{_NOT_ADMIT})"
        rf"{_SUFFIX}?(?={_TAIL}*$)"
    )),
    # 本鱼不敢认
    ("不敢认", re.compile(
        rf"(?:本鱼|我)(?:也|就|都|可|还)?(?:不敢|没法)认{_NOT_ADMIT}{_SUFFIX}?(?={_PUNCT}|$)"
    )),
    # 认了认了（叠字认账）
    ("认了认了", re.compile(r"认了认了")),
    # 改口套话：收回半句（正常人不会这么说）
    ("收回半句", re.compile(r"(?:先|就)?收回(?:刚才)?(?:那)?半句")),
]

FALLBACK_REPLY = "唔……好吧"


def find(text: str) -> list[str]:
    """返回命中的套话片段（去重保序）。"""
    body = text or ""
    out: list[str] = []
    for _, pattern in _PATTERNS:
        for match in pattern.finditer(body):
            hit = (match.group(0) or "").strip(" \t，,。！？!?；;~～…")
            if hit and hit not in out:
                out.append(hit)
    # 「我记下了」被「这个我记下了」包含时，只留长的那个
    return [h for h in out if not any(h != other and h in other for other in out)]


def strip(text: str) -> str:
    """把套话从句子里删掉，并收拾删完留下的孤立标点。"""
    body = text or ""
    for _, pattern in _PATTERNS:
        body = pattern.sub("", body)
    # 逗号后面直接接了句号/结尾，就把逗号也带走
    body = re.sub(r"[，,]\s*(?=[。！？!?~～…]|$)", "", body)
    # 省略号/破折号后面留了个逗号：「嗯……，以后」→「嗯……以后」
    body = re.sub(r"(…|——)\s*[，,]\s*", r"\1", body)
    # 删到句首/冒号后面只剩标点的情况
    body = re.sub(r"^\s*[，,。！？!?；;：:~～…]+", "", body)
    # 「那，反正……」这种被删出来的连接词逗号
    body = re.sub(r"^(那|所以|但是|不过|然后|而且)\s*[，,]\s*", "", body)
    body = re.sub(r"([，,]){2,}", "，", body)
    body = re.sub(r"[ \t]{2,}", " ", body)
    body = re.sub(r"\n{3,}", "\n\n", body)
    body = body.strip(" \t，,。！？!?；;：:~～…\n")
    # 句末裸表态删完只剩「这」「这张图」这种指代残渣：整句就剩它就别发了
    if re.fullmatch(r"(?:这|那)[^\s，,。！？!?]{0,3}", body):
        return ""
    return body


def retry_note(hit: str) -> str:
    """重说时给模型看的一句提示（不解释、不跳出人设）。"""
    hit = (hit or "").strip()
    if len(hit) > 20:
        hit = hit[:20]
    return (
        f"（刚才那句「{hit}」太像套话了。重说一句，用你平常的语气；"
        "别用这种固定句式，也别解释。）"
    )
