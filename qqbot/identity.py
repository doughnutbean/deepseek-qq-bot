"""「我叫什么 / 我是谁 / 我的QQ名是什么」：把说话人的昵称和号摆到眼前。

名字其实一直在消息行首（「【群友】昵称：话」），这一轮的说明里也写了
「你在回谁（QQ 号）」。但 2026-10-29 19:13 群 123456789，一只大肥鱼连着问
「我的QQ名字是什么」「那你能看见我的QQ名称吗」，她答：

    本鱼哪知道你叫什么呀，你自己还看不见吗
    看不见呀，本鱼这就一个头像和你要说的话

她看得见群名片/昵称，却把「群里改不了昵称」记成了「看不见昵称」。这里做两件
事，都是纯本地、0 token：

1. ``asks_identity``：认出这类问句。app 在这一轮的动态上下文里补一句
   「站在你面前的就是【群友】X（QQ 号）」；searchgate 也不再拿它去搜网页
   （「我的QQ名字是什么」曾被当成事实问题白搜一次，搜回来的东西还让她更
   坚信自己看不见名字）。
2. ``identity_note``：生成那句话，把「看得见」「直接答」「别说看不见」讲清楚。
"""

from __future__ import annotations

import re

# 命中就算在问「我自己是谁 / 我叫什么」。
# 注意别误伤「我是谁的主人」（问的是她养了谁）、「我家狗叫什么」（问宠物）。
_IDENTITY_ASK_RE = re.compile(
    # 我叫什么 / 我的QQ名是什么 / 我的ID是多少
    r"我\s*(?:的)?\s*(?:QQ|qq)?\s*"
    r"(?:昵称|群名片|名称|名字|姓名|名|ID|id|号|账号|帐号)?\s*"
    r"(?:是|叫|为|写成|显示成)\s*(?:什么|啥|多少)"
    # 我是谁 / 我是哪个（排除「我是谁的主人」）
    r"|我\s*(?:又|到底|究竟)?\s*是\s*(?:谁|哪个|哪一位)(?!\s*的)"
    # 你知道 / 记得 / 认得我是谁吗
    r"|你\s*(?:知道|记得|认得|认识|还知道|还记得)\s*我\s*(?:是|叫|吗|么|不|谁)"
    # 看 / 知道 / 记得 + 我的 + 名 / 号
    r"|(?:看|知道|记得|认得|认识)\s*(?:得|到|见)?\s*我\s*(?:的)?\s*(?:QQ|qq)?\s*"
    r"(?:昵称|群名片|名称|名字|姓名|名|ID|id|号)"
)


def asks_identity(text: str) -> bool:
    """这句是不是在问「我是谁 / 我叫什么」。纯规则、0 token。"""
    body = (text or "").strip()
    if not body:
        return False
    return bool(_IDENTITY_ASK_RE.search(body))


def identity_note(*, tag: str, nick: str, uid: str, is_owner: bool = False) -> str:
    """写进这一轮动态上下文的说明：说话人的名字就在眼前，直接答。

    ``tag`` 是身份标记（【群友】/【主人】/…），``nick`` 是消息行首那个昵称，
    ``uid`` 是 QQ 号。缺名字时退回号；两者都没有就只说「你就是你」。
    """
    who = str(nick or "").strip() or str(uid or "").strip()
    num = str(uid or "").strip()
    shown = f"{tag}{who}（QQ {num}）" if num else f"{tag}{who}"
    subject = "主人" if is_owner else "他"
    answer = f"「你不就是{who}嘛」" if who else "「就是你呀」"
    return (
        f"（{subject}在问自己叫什么 / 是谁：这一轮说话的就是{shown}。"
        "这个名字和号你**看得见**，就在消息行首和这一轮说明里；"
        f"直接按这个答，比如{answer}。"
        "别说「看不见」、别说不知道、也别反问他叫什么 —— "
        "名字你改不了，但看得见。）"
    )
